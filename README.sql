-- Descripción del caso
Este proyecto consiste en crear una base de datos llamada Ventas tech
con el fin de organizar la información mediante la creación de tablas. 

  Esta base de datos nos permitira organizar y administrar la información de las categorias,
  los productos, los clientes y las ventas. Su objetivo es facilitar el registro de las operaciones
  comerciales y la realización de consultas.
  
El motor utilizado fue Microsoft SQL Server siendo un sistema de gestión que nos permitio 
crear las tablas, insertar datos y realizar consultas.
  

 
